//! 多格式捕获 — 从剪贴板读多格式 + 分类
//!
//! 技术依据见 m2-research.md §三。两步:
//! 1. `classify_formats`(纯函数):UTI 列表 → 捕获决策(隐私跳过?捕获哪些?)
//! 2. `capture_multi`(系统交互):按决策读剪贴板内容 → 字节
//!
//! 阶段范围:文本/富文本(RTF/HTML)/文件 URL/图片(PNG/TIFF)。图片走 image_store 存盘,
//! file_path 存相对路径。

use std::path::Path;

use clipboard_rs::{Clipboard, ClipboardContent, ClipboardContext, ContentFormat};

use crate::clipboard::uti;
use crate::error::AppError;
use crate::models::ContentKind;

/// 捕获决策(classify_formats 的返回)。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CaptureDecision {
    /// 不捕获(隐私跳过 / 无白名单格式)。
    Skip,
    /// 捕获这些 UTI(已过滤隐私 + 噪音,只剩白名单成员)。
    Capture(Vec<String>),
}

/// 分类剪贴板的 UTI 列表,决定捕获哪些(纯函数,核心决策逻辑)。
///
/// 决策规则(优先级从高到低):
/// 1. 含隐私跳过标记(`ConcealedType`/`TransientType`/`AutoGeneratedType`)→ Skip(整条不入库)
/// 2. 过滤噪音(`dyn.*` + NOISE_UTIS)
/// 3. 取与白名单的交集
/// 4. 交集为空 → Skip;非空 → Capture(交集)
pub fn classify_formats(available_utis: &[String]) -> CaptureDecision {
    // 1. 隐私跳过:含任一标记 → 整条拒绝
    if uti::has_privacy_skip(available_utis) {
        return CaptureDecision::Skip;
    }

    // 2 + 3. 过滤噪音 + 取白名单交集(白名单天然排除非成员,噪音检查防御性叠加)
    let to_capture: Vec<String> = available_utis
        .iter()
        .filter(|u| !uti::is_noise(u))
        .filter(|u| uti::is_whitelisted(u))
        .cloned()
        .collect();

    if to_capture.is_empty() {
        CaptureDecision::Skip
    } else {
        CaptureDecision::Capture(to_capture)
    }
}

/// 根据捕获的 UTI 列表推断 contentKind(纯函数)。
///
/// 优先级:file-url → image(png/tiff)→ rtf/html → text。
/// - 含 file-url → File(不管还有什么)
/// - 含图片(png/tiff)→ Image(或 Mixed 若还有文本/富文本)
/// - 含 rtf/html → Rich(或 Mixed 若还有图片)
/// - 只有 text → Text
pub fn classify_content_kind(capture_utis: &[String]) -> ContentKind {
    let has_text = capture_utis.iter().any(|u| u == uti::UTI_PLAIN_TEXT);
    let has_rich = capture_utis
        .iter()
        .any(|u| u == uti::UTI_RTF || u == uti::UTI_HTML);
    let has_image = capture_utis
        .iter()
        .any(|u| u == uti::UTI_PNG || u == uti::UTI_TIFF);
    let has_file = capture_utis.iter().any(|u| u == uti::UTI_FILE_URL);

    // file-url 优先(文件场景标题取文件名)
    if has_file {
        // 文件 + 其他 → Mixed;纯文件 → File
        if has_text || has_rich || has_image {
            return ContentKind::Mixed;
        }
        return ContentKind::File;
    }

    // 图片分类(图片走 capture_and_store_image 存盘,此处按格式推断 kind)
    if has_image {
        if has_text || has_rich {
            return ContentKind::Mixed;
        }
        return ContentKind::Image;
    }

    if has_rich {
        return ContentKind::Rich;
    }

    // 默认(含 has_text 或兜底)
    ContentKind::Text
}

/// 一个捕获到的格式(uti + 字节内容 / 图片文件路径)。
///
/// 文本类格式(text/rtf/html/file-url):data 是字节内容,file_path 为 None。
/// 图片格式(png/tiff):data 为空,file_path 指向磁盘(由 image_store 存盘)。
#[derive(Debug, Clone)]
pub struct CapturedFormat {
    pub uti: String,
    pub data: Vec<u8>,
    /// 图片格式的磁盘相对路径(file_path)。文本类格式为 None。
    pub file_path: Option<String>,
}

/// 捕获的完整结果。
#[derive(Debug, Clone)]
pub struct CapturedContent {
    /// 所有格式(含图片)。
    pub formats: Vec<CapturedFormat>,
    /// 分类后的内容类型。
    pub kind: ContentKind,
    /// 图片尺寸(若含图片,用于标题「图片 W×H」)。None = 无图片。
    pub image_size: Option<(u32, u32)>,
}

/// 从剪贴板读取多格式内容(系统交互,非纯函数)。
///
/// 按 `capture_utis` 读取对应格式:
/// - 文本/富文本/文件 URL:读字节进 data
/// - 图片(png/tiff):get_image → to_png → image_store 存盘 → file_path
///
/// `images_dir` 为图片根目录(<app_data_dir>/images/),图片格式需要它存盘。
/// 返回 None 表示「无有效内容可捕获」。
pub fn capture_multi(
    clipboard: &ClipboardContext,
    capture_utis: &[String],
    images_dir: &Path,
) -> Result<Option<CapturedContent>, AppError> {
    let mut formats: Vec<CapturedFormat> = Vec::new();
    let mut image_size: Option<(u32, u32)> = None;

    // 文本类格式:批量读
    let text_like_utis: Vec<&str> = capture_utis
        .iter()
        .map(|s| s.as_str())
        .filter(|u| *u != uti::UTI_PNG && *u != uti::UTI_TIFF)
        .collect();
    if !text_like_utis.is_empty() {
        let req: Vec<ContentFormat> = text_like_utis
            .iter()
            .filter_map(|u| uti::uti_to_content_format(u))
            .collect();
        let contents = clipboard.get(&req).map_err(|e| {
            AppError::new(crate::error::codes::CLIPBOARD_READ_FAILED, format!("读剪贴板失败: {e}"))
        })?;
        for content in contents {
            if let Some(fmt) = content_to_captured(content) {
                formats.push(fmt);
            }
        }
    }

    // 图片格式:单独读 + 存盘
    let has_image = capture_utis.iter().any(|u| u == uti::UTI_PNG || u == uti::UTI_TIFF);
    if has_image {
        if let Some(img_fmt) = capture_and_store_image(clipboard, images_dir)? {
            image_size = Some((img_fmt.image_w, img_fmt.image_h));
            formats.push(CapturedFormat {
                uti: uti::UTI_PNG.to_string(),
                data: Vec::new(),
                file_path: Some(img_fmt.rel_path),
            });
        }
    }

    if formats.is_empty() {
        return Ok(None);
    }

    let captured_utis: Vec<String> = formats.iter().map(|f| f.uti.clone()).collect();
    let kind = classify_content_kind(&captured_utis);

    Ok(Some(CapturedContent { formats, kind, image_size }))
}

/// 图片捕获 + 存盘的中间结果。
struct StoredImage {
    rel_path: String,
    image_w: u32,
    image_h: u32,
}

/// 读剪贴板图片 → to_png → image_store 存盘。返回存盘元数据。
fn capture_and_store_image(
    clipboard: &ClipboardContext,
    images_dir: &Path,
) -> Result<Option<StoredImage>, AppError> {
    use clipboard_rs::common::RustImage;
    let img = match clipboard.get_image() {
        Ok(img) => img,
        Err(e) => {
            // 真实读剪贴板失败(非「无图格式」)也要降级跳过(不阻断其他格式捕获),
            // 但必须留日志,否则图片静默丢失无法排查。
            log::warn!("[capture] get_image 失败,跳过图片捕获: {e}");
            return Ok(None);
        }
    };
    let png_buffer = img.to_png().map_err(|e| {
        AppError::new(crate::error::codes::CLIPBOARD_READ_FAILED, format!("图片转 PNG 失败: {e}"))
    })?;
    let meta = crate::clipboard::image_store::save_image(png_buffer.get_bytes(), images_dir)?;
    Ok(Some(StoredImage {
        rel_path: meta.rel_path,
        image_w: meta.width,
        image_h: meta.height,
    }))
}

/// 把 clipboard-rs 的 ClipboardContent 转成 CapturedFormat(文本/富文本/文件)。
///
/// 图片格式(ClipboardContent::Image)在此不处理(图片走 capture_and_store_image 单独存盘)。
fn content_to_captured(content: ClipboardContent) -> Option<CapturedFormat> {
    match content {
        ClipboardContent::Text(s) => Some(CapturedFormat {
            uti: uti::UTI_PLAIN_TEXT.to_string(),
            data: s.into_bytes(),
            file_path: None,
        }),
        ClipboardContent::Rtf(s) => Some(CapturedFormat {
            uti: uti::UTI_RTF.to_string(),
            data: s.into_bytes(),
            file_path: None,
        }),
        ClipboardContent::Html(s) => Some(CapturedFormat {
            uti: uti::UTI_HTML.to_string(),
            data: s.into_bytes(),
            file_path: None,
        }),
        ClipboardContent::Files(paths) => Some(CapturedFormat {
            uti: uti::UTI_FILE_URL.to_string(),
            data: paths.join("\n").into_bytes(),
            file_path: None,
        }),
        // 图片走 capture_and_store_image;Other 不处理(白名单策略下不会有 Other)
        ClipboardContent::Image(_) | ClipboardContent::Other(_, _) => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn utis(list: &[&str]) -> Vec<String> {
        list.iter().map(|s| s.to_string()).collect()
    }

    // ===== classify_formats 测试 =====

    #[test]
    fn classify_skips_privacy_concealed() {
        // 密码管理器桌面 app:含 ConcealedType → 整条跳过
        let formats = utis(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]);
        assert_eq!(classify_formats(&formats), CaptureDecision::Skip);
    }

    #[test]
    fn classify_skips_privacy_transient() {
        let formats = utis(&["public.utf8-plain-text", "org.nspasteboard.TransientType"]);
        assert_eq!(classify_formats(&formats), CaptureDecision::Skip);
    }

    #[test]
    fn classify_captures_plain_text() {
        // 浏览器复制:含 text + html + 噪音 → 只捕获白名单
        let formats = utis(&[
            "public.utf8-plain-text",
            "public.html",
            "com.apple.WebKit.custom-pasteboard-data", // 噪音
        ]);
        let decision = classify_formats(&formats);
        match decision {
            CaptureDecision::Capture(utis) => {
                assert!(utis.contains(&"public.utf8-plain-text".to_string()));
                assert!(utis.contains(&"public.html".to_string()));
                assert!(!utis.contains(&"com.apple.WebKit.custom-pasteboard-data".to_string()));
            }
            _ => panic!("应捕获"),
        }
    }

    #[test]
    fn classify_captures_rich_text_from_word() {
        // Word 复制:text + rtf + html + 噪音
        let formats = utis(&[
            "public.utf8-plain-text",
            "public.rtf",
            "public.html",
            "com.apple.linkpresentation.metadata", // 噪音
        ]);
        let decision = classify_formats(&formats);
        match decision {
            CaptureDecision::Capture(utis) => {
                assert!(utis.contains(&"public.rtf".to_string()));
                assert_eq!(utis.len(), 3, "应捕获 text+rtf+html 三个,过滤噪音");
            }
            _ => panic!("应捕获"),
        }
    }

    #[test]
    fn classify_filters_dyn_uti() {
        let formats = utis(&["public.utf8-plain-text", "dyn.some-dynamic-uti"]);
        match classify_formats(&formats) {
            CaptureDecision::Capture(utis) => {
                assert_eq!(utis, vec!["public.utf8-plain-text".to_string()]);
            }
            _ => panic!("应捕获"),
        }
    }

    #[test]
    fn classify_skips_when_no_whitelist() {
        // 全是噪音/非白名单
        let formats = utis(&["com.apple.linkpresentation.metadata", "dyn.xxx"]);
        assert_eq!(classify_formats(&formats), CaptureDecision::Skip);
    }

    #[test]
    fn classify_skips_empty() {
        assert_eq!(classify_formats(&[]), CaptureDecision::Skip);
    }

    #[test]
    fn classify_captures_screenshot_png_tiff() {
        // 系统截图:png + tiff(classify 应判定为可捕获)
        let formats = utis(&["public.png", "public.tiff"]);
        match classify_formats(&formats) {
            CaptureDecision::Capture(utis) => {
                assert!(utis.contains(&"public.png".to_string()));
                assert!(utis.contains(&"public.tiff".to_string()));
            }
            _ => panic!("应捕获"),
        }
    }

    // ===== classify_content_kind 测试 =====

    #[test]
    fn kind_plain_text() {
        assert_eq!(classify_content_kind(&utis(&["public.utf8-plain-text"])), ContentKind::Text);
    }

    #[test]
    fn kind_rich_text() {
        // text + rtf + html → Rich
        let formats = utis(&["public.utf8-plain-text", "public.rtf", "public.html"]);
        assert_eq!(classify_content_kind(&formats), ContentKind::Rich);
    }

    #[test]
    fn kind_file() {
        // file-url(注释:alias-record 不在白名单,classify_content_kind 只看传入的已过滤 UTI)
        assert_eq!(classify_content_kind(&utis(&["public.file-url"])), ContentKind::File);
    }

    #[test]
    fn kind_image() {
        assert_eq!(classify_content_kind(&utis(&["public.png"])), ContentKind::Image);
        assert_eq!(classify_content_kind(&utis(&["public.tiff"])), ContentKind::Image);
    }

    #[test]
    fn kind_mixed_image_and_text() {
        let formats = utis(&["public.png", "public.utf8-plain-text"]);
        assert_eq!(classify_content_kind(&formats), ContentKind::Mixed);
    }

    #[test]
    fn kind_file_priority_over_others() {
        // file-url 优先级最高
        let formats = utis(&["public.file-url", "public.utf8-plain-text", "public.png"]);
        assert_eq!(classify_content_kind(&formats), ContentKind::Mixed);
    }
}
