//! UTI(Uniform Type Identifier)常量 + 白/黑名单策略
//!
//! 技术依据见 m2-research.md §三。策略照搬 Maccy(千万用户验证):
//! - **白名单**:只捕获这些 UTI(其余天然忽略)。text/rtf/html/png/tiff/file-url
//! - **隐私黑名单**:检测到这些「标记型 UTI」→ 整条 item 不入库(密码/临时内容)
//! - **噪音过滤**:dyn.* 动态 UTI 全过滤(每次内容可能不同,存了破坏去重)
//!
//! ⚠️ 密码管理器**桌面 app** 复制密码会标记 org.nspasteboard.ConcealedType(能防住);
//! **浏览器扩展**不标记(防不住,README 告知用户)。

use clipboard_rs::ContentFormat;

// ============================================================
// UTI 常量(白名单成员)
// ============================================================

/// 纯文本。
pub const UTI_PLAIN_TEXT: &str = "public.utf8-plain-text";
/// 富文本(RTF)。
pub const UTI_RTF: &str = "public.rtf";
/// HTML。
pub const UTI_HTML: &str = "public.html";
/// PNG 图片。
pub const UTI_PNG: &str = "public.png";
/// TIFF 图片。
pub const UTI_TIFF: &str = "public.tiff";
/// 文件 URL。
pub const UTI_FILE_URL: &str = "public.file-url";

// ============================================================
// Windows 剪贴板格式名(Win32 注册格式名,与 macOS UTI 完全不同)
// ============================================================

/// Windows 纯文本(CF_UNICODETEXT)。
pub const WIN_TEXT: &str = "Unicode Text Format";
/// Windows 旧式文本(CF_TEXT / OEM_TEXT)。
pub const WIN_TEXT_ANSI: &str = "Text Format";
/// Windows 富文本(RTF)。
pub const WIN_RTF: &str = "Rich Text Format";
/// Windows HTML。
pub const WIN_HTML: &str = "HTML Format";
/// Windows PNG。
pub const WIN_PNG: &str = "PNG";
/// Windows DIB(设备无关位图,截图常见)。
pub const WIN_DIB: &str = "CF_DIB";

// ============================================================
// 白名单(照搬 Maccy supportedTypes + Windows 格式名)
// ============================================================

/// 应捕获的 UTI/格式名集合。不在白名单里的格式直接忽略。
///
/// macOS 用 UTI(public.*),Windows 用 Win32 注册格式名(如 "Unicode Text Format")。
/// 两套格式名完全不同,必须都列入白名单。
pub const WHITELIST_UTIS: &[&str] = &[
    // macOS UTI
    UTI_PLAIN_TEXT,
    UTI_RTF,
    UTI_HTML,
    UTI_PNG,
    UTI_TIFF,
    UTI_FILE_URL,
    // Windows 格式名
    WIN_TEXT,
    WIN_TEXT_ANSI,
    WIN_RTF,
    WIN_HTML,
    WIN_PNG,
    WIN_DIB,
];

// ============================================================
// 隐私黑名单(nspasteboard.org 标准,检测到整条跳过)
// ============================================================

/// 隐私跳过标记:剪贴板含这些 UTI 之一时,**整条 item 不入库**。
///
/// 这是 [nspasteboard.org](http://nspasteboard.org/) 社区标准,Maccy/Alfred/Raycast 都遵守:
/// - ConcealedType:密码(1Password/Bitwarden 桌面 app)
/// - TransientType:临时内容(密码管理器一次性复制)
/// - AutoGeneratedType:程序生成
pub const PRIVACY_SKIP_UTIS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

// ============================================================
// 噪音过滤(这些 UTI 即使在白名单也忽略)
// ============================================================

/// 噪音 UTI:不存不报错。主要是应用内部元数据,每次复制内容会变(破坏去重)。
///
/// 注:M2 白名单策略下这些大多天然被排除(不在白名单),此列表用于显式记录 + 防御。
pub const NOISE_UTIS: &[&str] = &[
    "com.apple.linkpresentation.metadata",
    "com.apple.WebKit.custom-pasteboard-data",
    "org.chromium.web-custom-data",
    "org.chromium.source-url",
    "org.chromium.internal.source-rfh-token",
    "com.apple.notes.richtext",
    "org.nspasteboard.source",
    "org.nspasteboard.ModifiedType",
    "com.apple.is-remote-clipboard",
    "com.microsoft.ObjectLink",
    "com.microsoft.Link-Source",
    "com.apple.NSFilePromiseItem",
];

/// 动态 UTI 前缀(`dyn.*`)。动态 UTI 每次内容可能不同,全过滤。
pub const DYN_UTI_PREFIX: &str = "dyn.";

// ============================================================
// 辅助判定(纯函数,可测)
// ============================================================

/// 判断 UTI 是否为隐私跳过标记。
pub fn is_privacy_skip(uti: &str) -> bool {
    PRIVACY_SKIP_UTIS.contains(&uti)
}

/// 判断剪贴板的 UTI 列表是否含任一隐私跳过标记(整条不入库)。
pub fn has_privacy_skip(available_utis: &[String]) -> bool {
    available_utis.iter().any(|u| is_privacy_skip(u))
}

/// 判断 UTI 是否为噪音(噪音列表成员 或 dyn.* 前缀)。
pub fn is_noise(uti: &str) -> bool {
    uti.starts_with(DYN_UTI_PREFIX) || NOISE_UTIS.contains(&uti)
}

/// 判断 UTI 是否在白名单内。
pub fn is_whitelisted(uti: &str) -> bool {
    WHITELIST_UTIS.contains(&uti)
}

/// 判断格式名是否为纯文本(macOS + Windows)。
pub fn is_text(uti: &str) -> bool {
    uti == UTI_PLAIN_TEXT || uti == WIN_TEXT || uti == WIN_TEXT_ANSI
}

/// 判断格式名是否为富文本/HTML(macOS + Windows)。
pub fn is_rich(uti: &str) -> bool {
    uti == UTI_RTF || uti == UTI_HTML || uti == WIN_RTF || uti == WIN_HTML
}

/// 判断格式名是否为图片(macOS + Windows)。
pub fn is_image(uti: &str) -> bool {
    uti == UTI_PNG || uti == UTI_TIFF || uti == WIN_PNG || uti == WIN_DIB
}

/// 判断格式名是否为文件 URL(目前仅 macOS)。
pub fn is_file_url(uti: &str) -> bool {
    uti == UTI_FILE_URL
}

// ============================================================
// UTI → ContentFormat 映射(给 clipboard-rs get() 用)
// ============================================================

/// 把白名单 UTI/格式名映射成 clipboard-rs 的 ContentFormat(用于读取)。
///
/// 同时支持 macOS UTI 和 Windows 格式名:
/// - macOS: public.utf8-plain-text / public.rtf / public.html / public.png / public.tiff / public.file-url
/// - Windows: Unicode Text Format / Rich Text Format / HTML Format / PNG / CF_DIB
///
/// 注意:
/// - PNG/TIFF/DIB 都映射成 Image(get_image 读取)
/// - Windows 的 Files 格式(CF_HDROP)暂不映射(文件复制场景较少,后续补)
pub fn uti_to_content_format(uti: &str) -> Option<ContentFormat> {
    match uti {
        // macOS UTI
        UTI_PLAIN_TEXT => Some(ContentFormat::Text),
        UTI_RTF => Some(ContentFormat::Rtf),
        UTI_HTML => Some(ContentFormat::Html),
        UTI_PNG | UTI_TIFF => Some(ContentFormat::Image),
        UTI_FILE_URL => Some(ContentFormat::Files),
        // Windows 格式名
        WIN_TEXT | WIN_TEXT_ANSI => Some(ContentFormat::Text),
        WIN_RTF => Some(ContentFormat::Rtf),
        WIN_HTML => Some(ContentFormat::Html),
        WIN_PNG | WIN_DIB => Some(ContentFormat::Image),
        // 非白名单 UTI 返回 None(不读)
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn whitelist_contains_core_formats() {
        assert!(is_whitelisted(UTI_PLAIN_TEXT));
        assert!(is_whitelisted(UTI_RTF));
        assert!(is_whitelisted(UTI_HTML));
        assert!(is_whitelisted(UTI_PNG));
        assert!(is_whitelisted(UTI_TIFF));
        assert!(is_whitelisted(UTI_FILE_URL));
    }

    #[test]
    fn whitelist_excludes_noise() {
        assert!(!is_whitelisted("com.apple.linkpresentation.metadata"));
        assert!(!is_whitelisted("NSStringPboardType")); // 老式 UTI,不在白名单
        assert!(!is_whitelisted("dyn.some-dynamic-uti"));
    }

    #[test]
    fn privacy_skip_detects_concealed() {
        assert!(is_privacy_skip("org.nspasteboard.ConcealedType"));
        assert!(is_privacy_skip("org.nspasteboard.TransientType"));
        assert!(!is_privacy_skip("public.utf8-plain-text"));
    }

    #[test]
    fn has_privacy_skip_scans_list() {
        // 含 ConcealedType → 整条跳过
        let formats = vec![
            "public.utf8-plain-text".to_string(),
            "org.nspasteboard.ConcealedType".to_string(),
        ];
        assert!(has_privacy_skip(&formats));

        // 不含隐私标记
        let formats = vec!["public.utf8-plain-text".to_string()];
        assert!(!has_privacy_skip(&formats));
    }

    #[test]
    fn noise_detects_dyn_prefix_and_list() {
        assert!(is_noise("dyn.some-dynamic-uti"));
        assert!(is_noise("com.apple.linkpresentation.metadata"));
        assert!(is_noise("org.chromium.web-custom-data"));
        assert!(!is_noise("public.utf8-plain-text"));
        assert!(!is_noise("public.rtf"));
    }

    #[test]
    fn uti_to_content_format_maps_whitelist() {
        assert!(matches!(uti_to_content_format(UTI_PLAIN_TEXT), Some(ContentFormat::Text)));
        assert!(matches!(uti_to_content_format(UTI_RTF), Some(ContentFormat::Rtf)));
        assert!(matches!(uti_to_content_format(UTI_HTML), Some(ContentFormat::Html)));
        assert!(matches!(uti_to_content_format(UTI_PNG), Some(ContentFormat::Image)));
        assert!(matches!(uti_to_content_format(UTI_TIFF), Some(ContentFormat::Image)));
        assert!(matches!(uti_to_content_format(UTI_FILE_URL), Some(ContentFormat::Files)));
    }

    #[test]
    fn uti_to_content_format_returns_none_for_non_whitelist() {
        assert!(uti_to_content_format("NSStringPboardType").is_none());
        assert!(uti_to_content_format("dyn.xxx").is_none());
        assert!(uti_to_content_format("com.apple.linkpresentation.metadata").is_none());
    }

    // ===== Windows 格式名测试 =====

    #[test]
    fn whitelist_includes_windows_formats() {
        assert!(is_whitelisted(WIN_TEXT));
        assert!(is_whitelisted(WIN_TEXT_ANSI));
        assert!(is_whitelisted(WIN_RTF));
        assert!(is_whitelisted(WIN_HTML));
        assert!(is_whitelisted(WIN_PNG));
        assert!(is_whitelisted(WIN_DIB));
    }

    #[test]
    fn uti_helpers_recognize_windows_formats() {
        assert!(is_text("Unicode Text Format"));
        assert!(is_text("Text Format"));
        assert!(is_rich("Rich Text Format"));
        assert!(is_rich("HTML Format"));
        assert!(is_image("PNG"));
        assert!(is_image("CF_DIB"));
        assert!(!is_text("PNG"));
        assert!(!is_image("Unicode Text Format"));
    }

    #[test]
    fn uti_to_content_format_maps_windows_formats() {
        assert!(matches!(uti_to_content_format(WIN_TEXT), Some(ContentFormat::Text)));
        assert!(matches!(uti_to_content_format(WIN_TEXT_ANSI), Some(ContentFormat::Text)));
        assert!(matches!(uti_to_content_format(WIN_RTF), Some(ContentFormat::Rtf)));
        assert!(matches!(uti_to_content_format(WIN_HTML), Some(ContentFormat::Html)));
        assert!(matches!(uti_to_content_format(WIN_PNG), Some(ContentFormat::Image)));
        assert!(matches!(uti_to_content_format(WIN_DIB), Some(ContentFormat::Image)));
    }
}
